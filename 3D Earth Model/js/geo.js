function inPolygon(lon, lat, p) {
  let inside = false;
  for (let i = 0, j = p.length - 2; i < p.length; j = i, i += 2) {
    const xi = p[i], yi = p[i + 1], xj = p[j], yj = p[j + 1];
    if ((yi > lat) !== (yj > lat) && lon < xj + (lat - yj) * (xi - xj) / (yi - yj)) inside = !inside;
  }
  return inside;
}

function bbox(p) {
  let x0 = 180, x1 = -180, y0 = 90, y1 = -90;
  for (let i = 0; i < p.length; i += 2) { x0 = Math.min(x0, p[i]); x1 = Math.max(x1, p[i]); y0 = Math.min(y0, p[i + 1]); y1 = Math.max(y1, p[i + 1]); }
  return { p, x0, x1, y0, y1 };
}

function segDist(lon, lat, ax, ay, bx, by) {
  const k = Math.cos(lat * Math.PI / 180);
  const px = (lon - ax) * k, py = lat - ay, vx = (bx - ax) * k, vy = by - ay;
  const t = Math.min(1, Math.max(0, (px * vx + py * vy) / (vx * vx + vy * vy)));
  return Math.hypot(px - t * vx, py - t * vy);
}

function domeValue(f, lon, lat, exponent) {
  const dx = (lon - f.dome[0]) * Math.cos(lat * Math.PI / 180) / f.rx, dy = (lat - f.dome[1]) / f.ry;
  return Math.exp(-Math.pow(dx * dx + dy * dy, exponent));
}

function reliefAt(lon, lat) {
  const n = fbm(lon, lat);
  let best = 0;
  for (const f of RELIEF) {
    let v = 0;
    if (f.ridge) {
      let d = Infinity;
      for (let i = 0; i + 3 < f.ridge.length; i += 2) d = Math.min(d, segDist(lon, lat, f.ridge[i], f.ridge[i + 1], f.ridge[i + 2], f.ridge[i + 3]));
      v = f.h * Math.exp(-(d / f.w) * (d / f.w)) * (0.7 + 0.5 * n);
    } else if (f.dome) {
      v = f.h * domeValue(f, lon, lat, 2) * (0.85 + 0.3 * n);
    } else if (f.cap !== undefined) {
      const r = Math.abs(lat - f.cap) / f.r;
      v = f.h * Math.exp(-r * r * r * r);
    }
    best = Math.max(best, v);
  }
  return best;
}

function hash01(i, j) {
  let h = Math.imul(i * 374761393 + j * 668265263, 1274126177);
  h = Math.imul(h ^ (h >>> 13), 1274126177);
  return ((h ^ (h >>> 16)) >>> 0) / 4294967295;
}

